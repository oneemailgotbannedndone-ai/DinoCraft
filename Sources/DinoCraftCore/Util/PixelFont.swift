/// DinoCraft's 5×7 pixel font: upper and lower case, digits, punctuation and a few symbols.
/// Each glyph is 7 rows of 5 bits (16 is the leftmost pixel). Both apps draw their text with it.
public enum PixelFont {
    public static let width = 5
    public static let height = 7
    /// Horizontal distance from one character to the next, in font pixels.
    public static let advance = 6

    /// The rows for a character. Accented letters use their plain letter, and anything else unknown draws as "?".
    public static func rows(for character: Character) -> [UInt8] {
        if let rows = glyphs[character] { return rows }
        let plain = String(character).folding(options: .diacriticInsensitive, locale: nil)
        if plain.count == 1, let base = plain.first, let rows = glyphs[base] { return rows }
        let upper = String(character).uppercased().first ?? character
        return glyphs[upper] ?? glyphs["?"]!
    }

    /// True when the font has its own glyph for the character (not counting the "?" fallback).
    public static func hasGlyph(_ character: Character) -> Bool {
        if glyphs[character] != nil { return true }
        let plain = String(character).folding(options: .diacriticInsensitive, locale: nil)
        return plain.count == 1 && plain.first.map { glyphs[$0] != nil } == true
    }

